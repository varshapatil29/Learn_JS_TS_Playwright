let i = 0;

while (i < 10) {
    console.log(i);
    i++;
}

// both for and while loops can be used to achieve the same result, 
// but they have different syntax and use cases. 
// The for loop is typically used when the number of iterations is known beforehand,
//  while the while loop is used when the number of iterations is not known and depends on a condition being met.
 
let i1 = 0;
 for ( ;i1 < 10; i1++) {
     console.log(i1);
 }


